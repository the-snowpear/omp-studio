/**
 * StudioAgentHubService - presentation-neutral agent roster and control
 * service for the Studio Agent Hub (05_AGENT_HUB_AND_JOBS.md, WP-050..WP-053).
 *
 * Native semantics arrive exclusively through narrow injected ports:
 *   - roster/status .......... AgentRegistry (get/list/onChange)
 *   - lifecycle .............. AgentLifecycleManager (ensureLive/release/has)
 *   - unread counts .......... IrcBus (unreadCount)
 *   - spawn .................. the TaskTool structured-subagent path
 *   - transcript ............. the native incremental transcript reader
 *
 * The service never exposes session files, transcript paths, worktrees, or
 * native error messages. Generations are derived from native port events and
 * lifecycle outcomes (never from renderer input); transcript cursors are
 * opaque, signed tokens generated by this service instance.
 */

import { createHmac, randomBytes, timingSafeEqual } from "node:crypto";
