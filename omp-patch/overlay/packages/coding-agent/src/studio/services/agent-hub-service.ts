const MAX_LIST_LIMIT = 500;
const DEFAULT_TRANSCRIPT_PAGE = 50;
const MAX_TRANSCRIPT_PAGE = 100;
const DEFAULT_TRANSCRIPT_MESSAGE_TEXT = 64 * 1024;
const CURSOR_VERSION = "1";
