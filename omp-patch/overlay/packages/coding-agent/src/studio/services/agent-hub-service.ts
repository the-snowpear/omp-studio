export type StudioAgentStatus =
	| "starting"
	| "running"
	| "idle"
	| "parked"
	| "reviving"
	| "aborted"
	| "failed"
	| "released";

export type StudioAgentSendMode = "prompt" | "steer" | "followUp";

export type StudioAgentDeliveryOutcome = "injected" | "queued" | "woken" | "revived";

