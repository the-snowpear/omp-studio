/**
 * Live per-agent telemetry source. Structurally compatible with a port that
 * reads the agent's active AgentSession (cumulative usage, current model,
 * latest assistant gist) and surfaces its change events. All accessors must
 * be cheap or cached by the wiring; they run inside every roster projection.
 */
export interface StudioAgentTelemetryPort {
	/** Cumulative usage for the agent's active session; undefined when unavailable. */
	liveUsage(agentId: string): StudioAgentUsage | undefined;
	/** Current resolved model id for the active session; undefined when unknown. */
	liveModel(agentId: string): string | undefined;
	/** Short gist of the latest assistant output; undefined when unavailable. */
	liveSummary(agentId: string): string | undefined;
	/**
	 * Re-resolve the agent's current session attachment (e.g. after revive
	 * swapped the AgentSession). Cheap no-op when the session is unchanged.
	 */
	refresh(agentId: string): void;
	/**
	 * Best-effort change stream for the agent's live telemetry. The wiring
	 * keeps the newest session attached; resolving the same agent again must
	 * be a cheap no-op. Returns a no-op unsubscribe when no session is live.
	 */
	onChange(agentId: string, listener: () => void): () => void;
}

