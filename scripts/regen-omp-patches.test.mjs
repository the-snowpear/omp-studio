import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

test("patch regeneration includes staged and unstaged edits against the upstream pin", async t => {
  const directory = await mkdtemp(join(tmpdir(), "omp-seam-regen-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await cp(import.meta.dirname, join(directory, "scripts"), { recursive: true });
  const vendor = join(directory, "omp-patch/vendor/oh-my-pi");
  const patches = join(directory, "omp-patch/patches");
  const overlay = join(directory, "omp-patch/overlay/packages/coding-agent/src/studio");
  const git = (...args) => execFileSync("git", ["-C", vendor, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  await mkdir(join(vendor, "packages/coding-agent/src/studio"), { recursive: true });
  await mkdir(patches, { recursive: true });
  await mkdir(overlay, { recursive: true });
  git("init", "--quiet");
  git("config", "core.autocrlf", "false");
  const main = "packages/coding-agent/src/main.ts";
  const cli = "packages/coding-agent/src/cli.ts";
  await writeFile(join(vendor, main), "export const main = 1;\n");
  await writeFile(join(vendor, cli), "export const cli = 1;\n");
  git("add", "--", main, cli);
  git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "--quiet", "-m", "upstream");
  const upstreamCommit = git("rev-parse", "HEAD");
  await writeFile(join(vendor, main), "export const main = 2;\n");
  await writeFile(join(vendor, cli), "export const cli = 2;\n");
  git("add", "--", main, cli);
  await writeFile(join(vendor, cli), "export const cli = 2;\nexport const unstaged = true;\n");
  const bridge = 'const PATCHSET_VERSION = "studio.1";\n';
  await writeFile(join(overlay, "bridge-server.ts"), bridge);
  await writeFile(join(vendor, "packages/coding-agent/src/studio/bridge-server.ts"), bridge);
  await writeFile(join(patches, "series.json"), JSON.stringify({ upstreamCommit, patchsetVersion: "studio.1", patches: [] }));
  git("-C", directory, "init", "--quiet");
  const regenerate = () => execFileSync(process.execPath, [join(directory, "scripts/regen-omp-patches.mjs")], { cwd: directory, stdio: "pipe" });
  regenerate();
  const patchFile = join(patches, "0001-studio-cli-entry.patch");
  const patch = await readFile(patchFile, "utf8");
  assert.match(patch, /\+export const main = 2;/);
  assert.match(patch, /\+export const cli = 2;/);
  assert.match(patch, /\+export const unstaged = true;/);
  git("apply", "--reverse", "--check", patchFile);
  const series = await readFile(join(patches, "series.json"), "utf8");
  git("config", "core.abbrev", "16");
  regenerate();
  assert.equal(await readFile(patchFile, "utf8"), patch);
  assert.equal(await readFile(join(patches, "series.json"), "utf8"), series);
});
