import { describe, expect, it, vi } from "vitest";
import { ConversationWorkspaceStore, WORKSPACE_STORAGE_KEY } from "./store";

const a = { targetId: null, workspaceId: "a", sessionId: "chat-a" };
const b = { targetId: "ssh-b", workspaceId: "b", sessionId: "chat-b" };
describe("conversation workspace", () => {
  it("opens sidebar selections in new windows once windowed, keeping existing documents and partitions", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.openFromDirectory(a);
    expect(store.getSnapshot().views).toHaveLength(1);
    expect(store.getSnapshot().views[0]?.placement).toBe("main");
    store.float(first);
    const second = store.openFromDirectory(b);
    store.snapView(second, "halves", 1);
    const snap = store.getSnapshot().snap;
    const third = store.openFromDirectory({ ...a, sessionId: "third" });
    expect(store.getSnapshot().views).toHaveLength(3);
    expect(store.getSnapshot().snap).toBe(snap);
    expect(store.getSnapshot().views.find(view => view.id === third)?.placement).toBe("float");
    expect(store.documentFor(first)?.ref).toEqual(a);
    expect(store.documentFor(second)?.ref).toEqual(b);
    expect(store.openFromDirectory(a)).toBe(first);
    expect(store.getSnapshot().views).toHaveLength(3);
    expect(store.getSnapshot().activeViewId).toBe(first);
  });
  it("focuses the main, minimized and native conversation in place when selected from the sidebar", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    expect(store.openFromDirectory(a)).toBe(first);
    expect(store.getSnapshot().views.find(view => view.id === first)?.placement).toBe("main");
    store.setWindow(second, { minimized: true });
    expect(store.openFromDirectory(b)).toBe(second);
    expect(store.getSnapshot().views.find(view => view.id === second)?.minimized).toBe(false);
    store.setPin(second, "window");
    expect(store.openFromDirectory(b)).toBe(second);
    expect(store.getSnapshot().views.find(view => view.id === second)?.placement).toBe("native");
    expect(store.getSnapshot().views).toHaveLength(2);
  });
  it("returns to ordinary sidebar switching after the last conversation is docked", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a);
    store.float(first); store.dock(first);
    expect(store.openFromDirectory(b)).toBe(first);
    expect(store.getSnapshot().views).toHaveLength(1);
    expect(store.documentFor(first)?.ref).toEqual(b);
  });
  it("keeps separate preview drafts when creating new conversation windows", () => {
    const store = new ConversationWorkspaceStore(null, true);
    const first = store.open({ targetId: null, workspaceId: "p0", draftId: "draft-a" }, "float");
    const second = store.open({ targetId: null, workspaceId: "p0", draftId: "draft-b" }, "float");
    expect(first).not.toBe(second);
    expect(store.documentFor(first)?.ref.previewThreadId).toBe("t0");
    expect(store.documentFor(second)?.ref.previewThreadId).toBe("t0");
  });
  it("opens in the focused slot and focuses an existing conversation instead of duplicating it", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a);
    const second = store.open(b, "float");
    expect(store.getSnapshot().views).toHaveLength(2);
    expect(store.open(a)).toBe(first);
    expect(store.getSnapshot().activeViewId).toBe(first);
    store.open({ ...a, sessionId: "third" });
    expect(store.getSnapshot().views).toHaveLength(2);
    expect(store.documentFor(second)?.ref).toEqual(b);
    expect(store.getSnapshot().documents.some(doc => doc.ref.sessionId === a.sessionId)).toBe(true);
  });
  it("moves the same conversation between the original area, floating and native windows", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    const document = store.documentFor(first);
    store.float(first, { x: 20, y: 30, width: 600, height: 450 });
    expect(store.getSnapshot().views.filter(view => view.placement === "main")).toHaveLength(0);
    store.float(first, undefined, true);
    expect(store.documentFor(first)).toBe(document);
    store.dock(first);
    expect(store.getSnapshot().views.find(view => view.placement === "main")?.id).toBe(first);
    store.float(first);
    store.setWindow(first, { minimized: true });
    expect(store.getSnapshot().views.filter(view => view.placement === "main")).toHaveLength(0);
    store.open(a);
    expect(store.getSnapshot().views.find(view => view.id === first)?.minimized).toBe(false);
  });
  it("restores open views and geometry while keeping closed conversation memory out of persistence", () => {
    const memory = new Map<string, string>();
    const storage = { getItem: (key: string) => memory.get(key) ?? null, setItem: (key: string, value: string) => { memory.set(key, value); } };
    const store = new ConversationWorkspaceStore(storage);
    const first = store.open(a), second = store.open(b, "float");
    store.float(second, { x: 42, y: 50, width: 620, height: 500 }, true);
    store.close(first); store.flush();
    const restored = new ConversationWorkspaceStore(storage);
    expect(restored.getSnapshot().views).toHaveLength(1);
    expect(restored.documentFor(second)?.ref).toEqual(b);
    expect(restored.getSnapshot().views[0]?.placement).toBe("native");
    expect(restored.getSnapshot().documents.some(doc => doc.ref.sessionId === a.sessionId)).toBe(false);
    const before = memory.get(WORKSPACE_STORAGE_KEY);
    const preview = new ConversationWorkspaceStore(storage, true);
    preview.open(a, "float"); preview.flush();
    expect(memory.get(WORKSPACE_STORAGE_KEY)).toBe(before);
  });
  it("reclaims the single main area without discarding its previous conversation cache", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    store.dock(second);
    expect(store.getSnapshot().views).toHaveLength(1);
    expect(store.getSnapshot().views[0]?.id).toBe(second);
    expect(store.getSnapshot().documents.some(doc => doc.ref.sessionId === a.sessionId)).toBe(true);
    expect(store.open(a)).toBe(second);
    expect(store.getSnapshot().views.some(view => view.id === first)).toBe(false);
  });
  it("does not save real layout when only the preview workspace has been used", () => {
    const setItem = vi.fn();
    const store = new ConversationWorkspaceStore({ getItem: () => null, setItem }, false, false);
    store.flush();
    expect(setItem).not.toHaveBeenCalled();
    store.enablePersistence(); store.flush();
    expect(setItem).toHaveBeenCalledOnce();
  });
  it("keeps shared panel sizes stable across focus changes and restart", () => {
    const memory = new Map<string, string>();
    const storage = { getItem: (key: string) => memory.get(key) ?? null, setItem: (key: string, value: string) => { memory.set(key, value); } };
    const store = new ConversationWorkspaceStore(storage);
    const first = store.open(a), second = store.open(b, "float");
    store.shared({ panelWidth: 600, bottomHeight: 320 });
    store.activate(first);
    expect(store.getSnapshot()).toMatchObject({ panelWidth: 600, bottomHeight: 320 });
    store.activate(second);
    store.flush();
    expect(new ConversationWorkspaceStore(storage).getSnapshot()).toMatchObject({ panelWidth: 600, bottomHeight: 320 });
  });
  it("automatically places the main conversation beside the first snapped window without duplicating identities", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    const firstDocument = store.documentFor(first), secondDocument = store.documentFor(second);
    store.snapView(second, "halves", 1);
    expect(store.getSnapshot().snapAssistCell).toBeNull();
    expect(store.getSnapshot().views.find(view => view.id === first)?.placement).toBe("float");
    expect(store.getSnapshot().snap?.members).toEqual({ 0: first, 1: second });
    expect(store.getSnapshot().snapAssistCell).toBeNull();
    expect(store.getSnapshot().views).toHaveLength(2);
    expect(store.documentFor(first)).toBe(firstDocument);
    expect(store.documentFor(second)).toBe(secondDocument);
  });
  it("retains free geometry when displacing, changing templates and leaving a partition", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float"), third = store.open({ ...b, sessionId: "third" }, "float");
    const rect = { x: 42, y: 70, width: 620, height: 440 };
    store.float(second, rect);
    store.snapView(first, "columns", 0); store.snapView(second, "columns", 1); store.snapView(third, "columns", 2);
    store.snapView(first, "halves", 0);
    expect(store.getSnapshot().snap?.members).toEqual({ 0: first, 1: second });
    expect(store.snapCell(third)).toBeUndefined();
    store.snapView(third, "halves", 1);
    expect(store.snapCell(second)).toBeUndefined();
    expect(store.getSnapshot().views.find(view => view.id === second)?.rect).toEqual(rect);
    store.float(third, rect);
    expect(store.snapCell(third)).toBeUndefined();
    expect(store.documentFor(third)?.ref.sessionId).toBe("third");
  });
  it("keeps a maximized partition, frees a minimized partition and restores it only while vacant", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    store.snapView(first, "halves", 0); store.snapView(second, "halves", 1);
    store.setWindow(first, { maximized: true });
    expect(store.snapCell(first)).toBe(0);
    store.setWindow(first, { maximized: false });
    store.setWindow(first, { minimized: true });
    expect(store.snapCell(first)).toBeUndefined();
    store.activate(first);
    expect(store.snapCell(first)).toBe(0);
    store.setWindow(first, { minimized: true });
    store.snapView(second, "halves", 0);
    store.activate(first);
    expect(store.snapCell(first)).toBeUndefined();
    store.setPin(second, "window");
    expect(store.snapCell(second)).toBeUndefined();
  });
  it("restores snap ratios and members and migrates earlier canvas-relative floats once", () => {
    const memory = new Map<string, string>();
    const storage = { getItem: (key: string) => memory.get(key) ?? null, setItem: (key: string, value: string) => { memory.set(key, value); } };
    const store = new ConversationWorkspaceStore(storage);
    const first = store.open(a), second = store.open(b, "float");
    store.snapView(first, "quarters", 0); store.snapView(second, "quarters", 3);
    store.resizeSnap({ columns: [0.6], row: 0.4 }); store.flush();
    const restored = new ConversationWorkspaceStore(storage);
    expect(restored.getSnapshot().snap).toEqual(store.getSnapshot().snap);
    expect(restored.getSnapshot().snapAssistCell).toBeNull();
    const legacy = { ...store.getSnapshot(), version: 2, coordinateVersion: undefined, snap: undefined };
    memory.set(WORKSPACE_STORAGE_KEY, JSON.stringify(legacy));
    const migrated = new ConversationWorkspaceStore(storage);
    migrated.setGeometry({ x: 0, y: 40, width: 1400, height: 900 }, { x: 300, y: 80, width: 900, height: 700 });
    expect(migrated.getSnapshot().views[0]!.rect).toMatchObject({ x: 340, y: 80 });
    const rect = migrated.getSnapshot().views[0]!.rect;
    migrated.setGeometry({ x: 0, y: 40, width: 1400, height: 900 }, { x: 350, y: 80, width: 850, height: 700 });
    expect(migrated.getSnapshot().views[0]!.rect).toBe(rect);
  });
  it("keeps a minimized conversation and window mode when its last visible window is minimized", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a);
    store.float(first);
    expect(store.allWindowed()).toBe(true);
    const document = store.documentFor(first);
    store.setWindow(first, { minimized: true });
    expect(store.getSnapshot().views).toHaveLength(1);
    expect(store.getSnapshot().views[0]).toMatchObject({ id: first, placement: "float", minimized: true });
    expect(store.documentFor(first)).toBe(document);
    expect(store.getSnapshot().activeDocumentId).toBe(document?.id);
    expect(store.allWindowed()).toBe(true);
  });
  it("hands the shared chrome to the latest minimized conversation and starts a new one only when none is left", () => {
    const store = new ConversationWorkspaceStore(null);
    const first = store.open(a), second = store.open(b, "float");
    store.float(first);
    store.setWindow(first, { minimized: true });
    store.activate(second);
    store.close(second);
    expect(store.getSnapshot().views.map(view => view.id)).toEqual([first]);
    expect(store.getSnapshot().activeDocumentId).toBe(store.documentFor(first)?.id);
    expect(store.allWindowed()).toBe(true);
    store.close(first);
    expect(store.getSnapshot().views).toHaveLength(1);
    expect(store.getSnapshot().views[0]?.placement).toBe("main");
    expect(store.allWindowed()).toBe(false);
  });
  it("opens a new window in the active conversation's project and connection", () => {
    const store = new ConversationWorkspaceStore(null);
    store.float(store.open(b));
    const created = store.openNewWindow();
    expect(store.documentFor(created)?.ref).toMatchObject({ targetId: "ssh-b", workspaceId: "b" });
    expect(store.getSnapshot().views.find(view => view.id === created)?.placement).toBe("float");
  });
});
